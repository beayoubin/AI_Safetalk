CREATE TABLE permit_risk (
  risk_id VARCHAR(30) NOT NULL,
  permit_no VARCHAR(30) NOT NULL,
  hazard_code VARCHAR(20) NOT NULL,
  hazard_description TEXT NULL,
  likelihood TINYINT NULL,
  severity TINYINT NULL,
  risk_score INT GENERATED ALWAYS AS (CASE WHEN likelihood IS NULL OR severity IS NULL THEN NULL ELSE likelihood*severity END) STORED,
  risk_level VARCHAR(30) NOT NULL DEFAULT 'LOW',
  control_measures TEXT NULL,
  PRIMARY KEY(risk_id), KEY idx_pr_permit(permit_no), KEY idx_pr_hazard(hazard_code), KEY idx_pr_level(risk_level),
  CONSTRAINT fk_pr_permit FOREIGN KEY(permit_no) REFERENCES work_permit(permit_no) ON DELETE CASCADE,
  CONSTRAINT fk_pr_hazard FOREIGN KEY(hazard_code) REFERENCES code_hazard(hazard_code),
  CONSTRAINT fk_pr_risk_level FOREIGN KEY(risk_level) REFERENCES code_risk_level(risk_level),
  CONSTRAINT chk_pr_likelihood CHECK(likelihood IS NULL OR likelihood BETWEEN 1 AND 5),
  CONSTRAINT chk_pr_severity CHECK(severity IS NULL OR severity BETWEEN 1 AND 5)
) ENGINE=InnoDB COMMENT='작업허가별 위험성평가';

