CREATE TABLE auth_user (
  id BIGINT NOT NULL AUTO_INCREMENT,
  login_id VARCHAR(80) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  user_name VARCHAR(120) NOT NULL,
  role_name VARCHAR(40) NOT NULL DEFAULT '시스템 관리자',
  active_yn CHAR(1) NOT NULL DEFAULT 'Y',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  password_updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id), UNIQUE KEY uq_auth_user_login_id (login_id),
  CONSTRAINT chk_auth_user_active CHECK (active_yn IN ('Y','N'))
) ENGINE=InnoDB COMMENT='사용자 계정';

CREATE TABLE code_work_category (
  category_code VARCHAR(20) NOT NULL,
  category_name VARCHAR(100) NOT NULL,
  display_order INT NOT NULL DEFAULT 0,
  active_yn CHAR(1) NOT NULL DEFAULT 'Y',
  PRIMARY KEY (category_code), UNIQUE KEY uq_work_category_name(category_name),
  CONSTRAINT chk_category_active CHECK(active_yn IN ('Y','N'))
) ENGINE=InnoDB COMMENT='작업공정/대분류 기준정보';

CREATE TABLE code_risk_level (
  risk_level VARCHAR(30) NOT NULL,
  risk_label VARCHAR(100) NOT NULL,
  min_score INT NULL,
  max_score INT NULL,
  display_order INT NOT NULL DEFAULT 0,
  active_yn CHAR(1) NOT NULL DEFAULT 'Y',
  PRIMARY KEY(risk_level), CONSTRAINT chk_risk_active CHECK(active_yn IN ('Y','N'))
) ENGINE=InnoDB COMMENT='위험등급 기준정보';

CREATE TABLE code_work_shift (
